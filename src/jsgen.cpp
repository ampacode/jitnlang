// Драйвер nlang -> JS для .nlb (frontend/<name>.nlb ->
// static/frontend/<name>.js). Эмиссия самих узлов — в
// Node::javascript(vm) рядом с cpp() и eval().
#include "jsgen.h"
#include "nvm.h"
#include "ninclude.h"
#include "lexer.h"
#include "run.h" // stripComments
#include "parser/nparse.h"
#include <fstream>
#include <sstream>
#include <filesystem>
#include <algorithm>

namespace fs = std::filesystem;

std::string nlang_compile_to_js(Nvm& vm,
                                const std::vector<NodePtr>& stmts) {
    std::string out = "// generated by nlang -> js\n'use strict';\n\n";
    for (auto& st : stmts)
        out += js::stmt(st, vm) + "\n\n";
    return out;
}

static std::string nlb_src_dir(Nvm& vm) {
    return vm.source_dir.empty() ? "." : vm.source_dir;
}

std::string nlang_compile_nlb(Nvm& vm, const std::string& name) {
    std::string dir = nlb_src_dir(vm);
    std::string src = dir + "/frontend/" + name + ".nlb";
    std::ifstream f(src, std::ios::binary);
    if (!f) return "";
    std::stringstream ss; ss << f.rdbuf();
    // .nlb — C-стиль { }: разрешаем явные блоки (nlb = nlang browser)
    Lexer lexer;
    NParser parser;
    parser.allow_braces = true;
    // indent-блоки выключены: .nlb — чистый C-стиль { } и ';'
    auto toks = lexer.tokenize(stripComments(ss.str()), false);
    if (std::getenv("NLANG_DUMP_NLB"))
        for (auto& t : toks)
            fprintf(stderr, "  %d '%s' syn=%d\n", t.type,
                    t.text.c_str(), (int)t.synthetic);
    auto stmts = parser.program(toks);

    std::string code = nlang_compile_to_js(vm, stmts);
    std::string out = dir + "/static/frontend/" + name + ".js";
    fs::create_directories(fs::path(out).parent_path());
    // переписываем только если изменилось (mtime-stable)
    bool write = true;
    {
        std::ifstream cur(out, std::ios::binary);
        if (cur) {
            std::stringstream cs; cs << cur.rdbuf();
            write = cs.str() != code;
        }
    }
    if (write) {
        std::ofstream o(out, std::ios::binary);
        o << code;
    }
    return "/frontend/" + name + ".js";
}

void nlang_compile_all_nlb(Nvm& vm) {
    std::string dir = nlb_src_dir(vm) + "/frontend";
    if (!fs::is_directory(dir)) return;
    std::vector<std::string> names;
    for (auto& e : fs::directory_iterator(dir))
        if (e.path().extension() == ".nlb")
            names.push_back(e.path().stem().string());
    std::sort(names.begin(), names.end());
    for (auto& n : names) nlang_compile_nlb(vm, n);
}

std::string nlang_resolve_nlb_attr(const std::string& aval, Nvm& vm) {
    if (aval.size() < 4 ||
        aval.substr(aval.size() - 4) != ".nlb")
        return aval;
    auto p = aval.find_last_of('/');
    std::string name = aval.substr(
        p == std::string::npos ? 0 : p + 1,
        aval.size() - (p == std::string::npos ? 0 : p + 1) - 4);
    std::string url = nlang_compile_nlb(vm, name);
    return url.empty() ? aval : url;
}
